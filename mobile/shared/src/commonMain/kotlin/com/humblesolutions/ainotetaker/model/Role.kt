package com.humblesolutions.ainotetaker.model

/**
 * The seven roles, and the single number that orders them.
 *
 * `level` is not decoration — it is what the Firestore rules compare against a
 * custom claim, so these numbers are a contract with the backend and with the
 * web prototype's `src/lib/roles.js`. Changing one here without changing the
 * rules locks people out of their own data.
 */
enum class Role(val id: String, val level: Int) {
    SUPER_ADMIN("superAdmin", 1),
    ADMIN("admin", 2),
    ZONE_LEADER("zoneLeader", 3),
    WARD_LEADER("wardLeader", 4),
    BOOTH_LEADER("boothLeader", 5),
    /**
     * A young person who vouches for how many people they can bring out —
     * their "strength". A RECORD LIKE A LOCALITY MEMBER, never a user: no
     * login, nobody beneath them, added by exactly the people who add
     * Locality Members.
     *
     * THE SAME LEVEL AS A LOCALITY MEMBER, ON PURPOSE. "Just above" them is
     * where they are LISTED — declared before [BOOTH_MEMBER], so [ordered]
     * (a stable sort) puts them first everywhere. A level of their own would
     * have meant renumbering every Locality Member already stored, in the
     * rules and on the web, for nothing a Youth Leader can use: they neither
     * sign in nor add anybody. Decided with Rishi, 27 Sep 2026.
     */
    YOUTH_LEADER("youthLeader", 6),
    BOOTH_MEMBER("boothMember", 6),

    /**
     * a CRM login from a department or office, the CRM's
     * `contributor` role. They sign in and record their own meetings like
     * anybody else, and manage nobody, so they sit below every TAS level.
     * Never offered by [creatableRoles]: CRM logins are made on the CRM.
     */
    CONTRIBUTOR("contributor", 7);

    /**
     * Whether this role signs in at all.
     *
     * A BOOTH MEMBER NEVER DOES, and that is the whole distinction. They are a
     * RECORD — somebody canvassed, counted and contactable — not a user of the
     * app. They have no screen to open, nothing to submit and nobody beneath
     * them to register, so an account for them would be a credential that
     * exists only to be leaked.
     *
     * The consequences run all the way down: no username, no password, no
     * Firebase identity, and no custom claims. Their `users/{id}` document is
     * created and read by the people above them, and the document id is
     * generated by Firestore rather than by Auth, because there is no Auth uid
     * to borrow.
     *
     * THEIR PHONE NUMBER IS STILL UNIQUE. It is how a booth leader reaches
     * them on the day, and two records sharing one number is still a mistake
     * worth refusing — it just stopped being a credential clash and became a
     * data-quality one.
     */
    val signsIn: Boolean get() = this != BOOTH_MEMBER && this != YOUTH_LEADER

    /**
     * Registered on the card — the voter-list screen, then the tabbed form a
     * worker fills on a doorstep — rather than the office's step-by-step
     * wizard. The two roles that are records, not users.
     */
    val onCard: Boolean get() = this == BOOTH_MEMBER || this == YOUTH_LEADER

    companion object {
        /** Backend strings are the source of truth; an unknown one is not a crash. */
        fun fromId(id: String?): Role? = entries.firstOrNull { it.id == id }

        /**
         * the role the CRM API reports in `GET /api/me`
         * (`super_admin`, `admin`, `contributor`; see `permissions.js` in the
         * CRM server). An unknown one is null, not a crash, as above.
         */
        fun fromCrmRole(role: String?): Role? = when (role) {
            "super_admin" -> SUPER_ADMIN
            "admin" -> ADMIN
            "contributor" -> CONTRIBUTOR
            // AI Notebook: the server's two roles.
            "member" -> CONTRIBUTOR
            else -> null
        }

        /** Highest authority first — the order every picker and list uses. */
        val ordered: List<Role> = entries.sortedBy { it.level }
    }
}


/** Super Admin and Admin are global; everyone else is scoped to their branch. */
fun Role?.isAdminOrAbove(): Boolean = this != null && level <= 2

/** A Booth Member manages nobody, so whole sections of the app do not apply. */
fun Role?.managesPeople(): Boolean = this != null && level < 6

/**
 * Every role this one could register — strictly below it, and never a Super
 * Admin. An Admin may create a Booth Member directly without stepping through
 * the levels between; Booth Member is a leaf and creates nobody.
 *
 * WHAT THE ROLE COULD ADD, NOT WHAT THIS PERSON IS OFFERED. A Youth Leader is
 * offered only to whoever has `Feature.YOUTH_LEADER` (Ansh, 10 Oct 2026) — ask
 * `FeatureAccess.addableRoles` for the list a screen draws. The server
 * (`createTeamMember`) knows `youthLeader` since 26 Sep 2026.
 */
fun Role?.creatableRoles(): List<Role> {
    val mine = this?.level ?: return emptyList()
    // a Contributor is a CRM login, made on the CRM, never here.
    return Role.ordered.filter { it.level > mine && it != Role.SUPER_ADMIN && it != Role.CONTRIBUTOR }
}
