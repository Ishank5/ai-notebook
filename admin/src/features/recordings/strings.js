const plural = new Intl.PluralRules("en");

function lookup(path) {
  let node = EN;
  for (const part of path.split(".")) {
    if (node === null || typeof node !== "object" || !(part in node)) return undefined;
    node = node[part];
  }
  return typeof node === "string" ? node : undefined;
}

/**
 * i18next's `t`, for this one table. "common:action.cancel" reads the borrowed
 * common word; a missing key gives `defaultValue`, else the key itself, as
 * i18next does.
 */
export function t(key, options = {}) {
  const path = String(key).replace(/^common:/, "common.");
  let text;
  if (typeof options.count === "number") {
    text = lookup(`${path}_${plural.select(options.count)}`) ?? lookup(`${path}_other`);
  }
  text ??= lookup(path);
  if (text === undefined) text = options.defaultValue ?? key;
  return text.replace(/\{\{\s*(\w+)\s*\}\}/g, (_, name) => (options[name] ?? "") + "");
}
